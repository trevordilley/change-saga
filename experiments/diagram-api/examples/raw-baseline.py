#!/usr/bin/env python3
"""Controlled raw-SVG workflow, not an independent model-authorship benchmark.
Use identical starting artwork, fonts and icons. Commands edit literal SVG nodes.
Shared font/license payloads are supplied locally and excluded from both sides'
authoring comparison, while artifact transfers remain separately reported.
"""
import base64,json,pathlib,re,subprocess,sys
D=pathlib.Path(sys.argv[1]).resolve();raw=D/'raw.svg';traffic=[]
svg=(D/'before.svg').read_text()
# Keep the font identical, but do not pretend an AI would type its base64 data.
font=re.search(r'base64,([^)]*)',svg).group(1);(D/'go-regular.ttf').write_bytes(base64.b64decode(font))
svg=svg.replace('data:font/ttf;base64,'+font,'./go-regular.ttf')
# Notices are distributed as a shared local input instead of AI-authored text.
notice=re.search(r'<metadata.*?</metadata>',svg,re.S).group();(D/'raw-notices.xml').write_text(notice);svg=svg.replace(notice,'')
def run(code,payload='',artifact=None,okay=True):
    args=['python3','-c',code,str(raw)]
    p=subprocess.run(args,input=payload.encode(),capture_output=True)
    traffic.append(dict(argv=args,request_bytes=len(' '.join(args).encode())+len(payload.encode()),response_bytes=len(p.stdout)+len(p.stderr),exit=p.returncode))
    if artifact:(D/artifact).write_bytes(p.stdout)
    if okay and p.returncode:raise RuntimeError(p.stderr.decode())
run("import pathlib,sys;pathlib.Path(sys.argv[1]).write_text(sys.stdin.read())",svg)
header="import xml.etree.ElementTree as E,sys;E.register_namespace('','http://www.w3.org/2000/svg');t=E.parse(sys.argv[1]);r=t.getroot();ns={'s':'http://www.w3.org/2000/svg'};"
footer="t.write(sys.argv[1],encoding='unicode')"
# Full SVG reading at creation; then a targeted path read after moving a node.
run("import pathlib,sys;print(pathlib.Path(sys.argv[1]).read_text())",artifact='raw-read.svg')
run(header+"r.find(\".//*[@id='validator']\").set('transform','translate(445 235)');"+footer)
run(header+"g=r.find(\".//*[@id='publish']\");print(g.attrib);print(g.find('s:path',ns).attrib)",artifact='raw-targeted.txt')
code=header+"g=r.find(\".//*[@id='validator']\");g.find('s:text/s:tspan',ns).text='Validate batch';g.find('s:rect',ns).set('fill','#ffffff');g.find('s:rect',ns).set('stroke','#64748b');"
# Update the node's text and icon ink to the normal style, just as the API does.
code+="[(e.set('fill','#172033')) for e in g.findall('s:text',ns)];g.find('s:svg',ns).set('color','#172033');"
for id,path in [('batch','M345 280 L410 280 L410 310 L445 310'),('publish','M775 310 L845 310 L845 280 L920 280'),('failure','M610 385 L610 495 L375 495')]:
    code+=f"r.find(\".//*[@id='{id}']/s:path\",ns).set('d',{path!r});"
# A temporary edge is an explicit group and path; it is removed in the next step.
code+="g=E.SubElement(r,'{http://www.w3.org/2000/svg}g',{'id':'temporary','data-from':'published','data-to':'validator'});E.SubElement(g,'{http://www.w3.org/2000/svg}path',{'d':'M920 350L775 350','stroke':'#94a3b8','fill':'none'});"+footer
run(code)
run(header+"r.remove(r.find(\".//*[@id='temporary']\"));"+footer)
run("import pathlib,sys;print(pathlib.Path(sys.argv[1]).read_text())",artifact='raw-final.svg')
report=dict(method='Controlled equivalent SVG edits; starting artwork generated by prototype, not independently hand-authored. No metadata transactions, retry safety, merge or recovery equivalent. Shared font and notices local. Counts are actual argv/stdin/stdout/stderr bytes, not tokens.',commands=len(traffic),request_bytes=sum(x['request_bytes'] for x in traffic),response_bytes=sum(x['response_bytes'] for x in traffic),traffic=traffic)
(D/'raw-traffic.json').write_text(json.dumps(report,indent=2)+'\n');print(json.dumps({k:v for k,v in report.items() if k!='traffic'}))
